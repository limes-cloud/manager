// menuNode 注册菜单节点参数
type menuNode struct {
	title      string // 菜单标题
	path       string // 接口路径
	method     string // HTTP 方法
	permission string // 权限标识
}

func api(n menuNode) *types.RegisterMenuNode {
	return apiNode(entity.MenuTypeApi, n)
}

func basic(n menuNode) *types.RegisterMenuNode {
	return apiNode(entity.MenuTypeBasic, n)
}

func apiNode(tp string, n menuNode) *types.RegisterMenuNode {
	node := &types.RegisterMenuNode{
		Title:  n.title,
		Type:   tp,
		Api:    value.Pointer(n.path),
		Method: value.Pointer(n.method),
		Weight: value.Pointer[int32](0),
	}
	if n.permission != "" {
		node.Permission = value.Pointer(n.permission)
	}
	return node
}
