func api(title string, path string, method string, permission string) *types.RegisterMenuNode {
	return apiNode(entity.MenuTypeApi, title, path, method, permission)
}

func basic(title string, path string, method string, permission string) *types.RegisterMenuNode {
	return apiNode(entity.MenuTypeBasic, title, path, method, permission)
}

func apiNode(tp string, title string, path string, method string, permission string) *types.RegisterMenuNode {
	node := &types.RegisterMenuNode{
		Title:  title,
		Type:   tp,
		Api:    value.Pointer(path),
		Method: value.Pointer(method),
		Weight: value.Pointer[int32](0),
	}
	if permission != "" {
		node.Permission = value.Pointer(permission)
	}
	return node
}
